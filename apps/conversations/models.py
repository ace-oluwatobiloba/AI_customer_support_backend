import uuid

from django.conf import settings
from django.db import models


class Conversation(models.Model):
    """
    Represents a customer support conversation.

    A conversation may begin as an AI chat and later become associated
    with a formal support ticket when escalation or ticket creation
    becomes necessary.
    """

    class Status(models.TextChoices):
        ACTIVE = "ACTIVE", "Active"
        ESCALATED = "ESCALATED", "Escalated"
        AGENT_ACTIVE = "AGENT_ACTIVE", "Agent Active"
        RESOLVED = "RESOLVED", "Resolved"
        CLOSED = "CLOSED", "Closed"

    # UUIDs prevent exposing sequential database IDs through the API.
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    # Every conversation belongs to one customer.
    # PROTECT preserves the conversation if someone attempts to
    # delete the associated user.
    customer = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        related_name="conversations",
    )

    # A conversation can exist before a formal ticket is created.
    # One conversation can therefore be associated with zero or one ticket.
    ticket = models.OneToOneField(
        "support.Ticket",
        on_delete=models.PROTECT,
        blank=True,
        null=True,
        related_name="conversation",
    )

    # A short human-readable title helps agents identify conversations
    # without opening the entire message history.
    title = models.CharField(
        max_length=255,
        blank=True,
    )

    # Tracks the lifecycle of the conversation.
    status = models.CharField(
        max_length=20,
        choices=Status.choices,
        default=Status.ACTIVE,
        db_index=True,
    )

    # Records when the conversation actually began.
    started_at = models.DateTimeField(
        auto_now_add=True,
    )

    # Remains NULL while the conversation is still active.
    ended_at = models.DateTimeField(
        blank=True,
        null=True,
    )

    # Standard record-maintenance timestamps.
    created_at = models.DateTimeField(
        auto_now_add=True,
    )

    updated_at = models.DateTimeField(
        auto_now=True,
    )

    def __str__(self):
        # The customer's email makes the object useful when debugging
        # or inspecting it in Django's shell/admin.
        return f"{self.title or 'Conversation'} - {self.customer.email}"

class Message(models.Model):
    """
    Represents one individual message inside a conversation.

    A message can come from the customer, an AI assistant, a human
    agent, or the system itself.
    """

    class SenderType(models.TextChoices):
        # A message written by the customer.
        CUSTOMER = "CUSTOMER", "Customer"

        # A response generated by the AI assistant.
        AI = "AI", "AI"

        # A response written by a human support agent.
        AGENT = "AGENT", "Agent"

        # Replies written by an administrator acting as support staff.
        ADMIN = "ADMIN", "Administrator"

        # Internal/system-generated events or notifications.
        SYSTEM = "SYSTEM", "System"

    # UUID prevents sequential message IDs from being exposed externally.
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    # Every message belongs to exactly one conversation.
    conversation = models.ForeignKey(
        Conversation,
        on_delete=models.PROTECT,
        related_name="messages",
    )

    # Customer/agent messages can be associated with an authenticated
    # user. AI and system messages normally have no human sender.
    sender_user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        blank=True,
        null=True,
        related_name="conversation_messages",
    )

    # This explicitly identifies the origin of the message.
    sender_type = models.CharField(
        max_length=20,
        choices=SenderType.choices,
    )

    # The actual message sent by the participant or generated by AI.
    content = models.TextField()

    # Stores the AI model used to generate an AI response.
    # It remains NULL for customer, agent, and system messages.
    model = models.CharField(
        max_length=100,
        blank=True,
        null=True,
    )

    # Flexible metadata allows us to store information such as:
    # token usage, latency, retrieval information, or provider IDs
    # without changing the database schema for every new AI feature.
    metadata = models.JSONField(
        default=dict,
        blank=True,
    )

    created_at = models.DateTimeField(
        auto_now_add=True,
    )

    updated_at = models.DateTimeField(
        auto_now=True,
    )

    def __str__(self):
        return (
            f"{self.sender_type} message "
            f"in {self.conversation_id}"
        )

class MessageRevision(models.Model):
    """
    Stores the previous content of an edited message.

    We keep revisions separately so editing a message does not destroy
    the original conversation history.
    """

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    # The message whose previous version is being preserved.
    message = models.ForeignKey(
        Message,
        on_delete=models.PROTECT,
        related_name="revisions",
    )

    # The user who performed the edit.
    revised_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        related_name="message_revisions",
    )

    # The content before the message was edited.
    previous_content = models.TextField()

    # Revision number makes the history easy to order and inspect.
    revision_number = models.PositiveIntegerField()

    revised_at = models.DateTimeField(
        auto_now_add=True,
    )

    class Meta:
        # A message cannot have two revisions with the same number.
        constraints = [
            models.UniqueConstraint(
                fields=["message", "revision_number"],
                name="unique_message_revision_number",
            ),
        ]

        # Most recent revisions should appear first when querying history.
        ordering = ["-revision_number"]

    def __str__(self):
        return (
            f"Revision {self.revision_number} "
            f"of message {self.message_id}"
        )